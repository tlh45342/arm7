.syntax unified
.arm
.global _start

_start:
    @ r6 = 0x0010_0000 (base for result/flag storage)
    movw    r6, #0
    movt    r6, #0x0010

    @ ------------------------------------------------
    @ Case 1: r0 = 0x80000001, LSR #1 -> r1
    @ Expect: r1 = 0x40000000, C = 1, N = 0, Z = 0
    @ ------------------------------------------------
    movw    r0, #1
    movt    r0, #0x8000          @ r0 = 0x80000001

    movs    r1, r0, lsr #1       @ lsrs r1, r0, #1
    mrs     r7, cpsr

    str     r1, [r6, #0]         @ [0x00100000] <= r1
    str     r7, [r6, #4]         @ [0x00100004] <= cpsr

    @ ------------------------------------------------
    @ Case 2: same r0, LSR #31 -> r2
    @ Expect: r2 = 0x00000001, C = 0, N = 0, Z = 0
    @ ------------------------------------------------
    movs    r2, r0, lsr #31      @ lsrs r2, r0, #31
    mrs     r7, cpsr

    str     r2, [r6, #8]         @ [0x00100008] <= r2
    str     r7, [r6, #12]        @ [0x0010000C] <= cpsr

    @ ------------------------------------------------
    @ Case 3: r0 = 0xFFFFFFFF, LSR #1 -> r3
    @ Expect: r3 = 0x7FFFFFFF, C = 1, N = 0, Z = 0
    @ ------------------------------------------------
    movw    r0, #0xFFFF
    movt    r0, #0xFFFF          @ r0 = 0xFFFFFFFF

    movs    r3, r0, lsr #1       @ lsrs r3, r0, #1
    mrs     r7, cpsr

    str     r3, [r6, #16]        @ [0x00100010] <= r3
    str     r7, [r6, #20]        @ [0x00100014] <= cpsr

    @ ------------------------------------------------
    @ Case 4: r0 = 0x00000001, LSR #1 -> r4
    @ Expect: r4 = 0x00000000, C = 1, Z = 1 (N = 0)
    @ ------------------------------------------------
    movw    r0, #1
    movt    r0, #0x0000          @ r0 = 0x00000001

    movs    r4, r0, lsr #1       @ lsrs r4, r0, #1
    mrs     r7, cpsr

    str     r4, [r6, #24]        @ [0x00100018] <= r4
    str     r7, [r6, #28]        @ [0x0010001C] <= cpsr

    @ ------------------------------------------------
    @ Case 5: r0 = 0x80000000, LSR #32 -> r5
    @ (LSR #0 encodes as LSR #32 in the immediate form)
    @ Expect: r5 = 0x00000000, C = 1, Z = 1
    @ ------------------------------------------------
    movw    r0, #0
    movt    r0, #0x8000          @ r0 = 0x80000000

    movs    r5, r0, lsr #32      @ lsrs r5, r0, #32 (encoded with imm=0)
    mrs     r7, cpsr

    str     r5, [r6, #32]        @ [0x00100020] <= r5
    str     r7, [r6, #36]        @ [0x00100024] <= cpsr

    @ ------------------------------------------------
    @ Done
    @ ------------------------------------------------
    bkpt    #0x1234
